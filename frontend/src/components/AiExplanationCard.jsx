import React, { useState } from 'react'
import { Copy, Check, Download, Lightbulb, AlertCircle } from 'lucide-react'
import MarkdownRenderer, { renderInline } from './MarkdownRenderer'
import { getSeverity } from '../lib/severity'
import { exportPdf } from '../services/api'

// Supports both the current API contract (why / what_to_do) and the legacy
// schema aliases (why_flagged / recommended_actions).
function normalizeExplanation(explanation) {
  if (!explanation) {
    return { summary: '', why: [], whatToDo: [], educationalTip: '' }
  }
  return {
    summary: explanation.summary || '',
    why: explanation.why || explanation.why_flagged || [],
    whatToDo: explanation.what_to_do || explanation.recommended_actions || [],
    educationalTip: explanation.educational_tip || '',
  }
}

// Builds a clean, portable Markdown report combining deterministic scan
// results with the grounded AI explanation for 1-click export / copy.
export function buildMarkdownReport(scanData, explanation) {
  const exp = normalizeExplanation(explanation)
  const lines = []
  const generatedAt = new Date().toISOString()

  lines.push('# CyberGuardian - AI Threat Explanation Report')
  lines.push('')
  lines.push('**Generated:** ' + generatedAt)
  lines.push('')

  if (scanData) {
    const target =
      scanData.url ||
      scanData.message ||
      (scanData.evidence && scanData.evidence.extracted_text) ||
      'N/A'
    const score =
      scanData.risk_assessment && scanData.risk_assessment.score !== undefined
        ? scanData.risk_assessment.score
        : 'N/A'
    const level =
      (scanData.risk_assessment && scanData.risk_assessment.level) || 'N/A'
    const mlProb = scanData.evidence ? scanData.evidence.ml_probability : null

    lines.push('## Scan Overview')
    lines.push('- **Target:** ' + target)
    lines.push('- **Risk Level:** ' + level)
    lines.push('- **Composite Risk Score:** ' + score + '/100')
    if (mlProb !== null && mlProb !== undefined) {
      lines.push('- **ML Phishing Probability:** ' + (mlProb * 100).toFixed(1) + '%')
    }

    if (scanData.risk_assessment && scanData.risk_assessment.triggers && scanData.risk_assessment.triggers.length) {
      lines.push('')
      lines.push('### Deterministic Triggers')
      scanData.risk_assessment.triggers.forEach(function (t) {
        lines.push('- ' + t)
      })
    }
    lines.push('')
  }

  lines.push('## Executive Summary')
  lines.push(exp.summary || 'No summary provided.')
  lines.push('')

  if (exp.why.length) {
    lines.push('## Why Was This Flagged?')
    exp.why.forEach(function (item) {
      lines.push('- ' + item)
    })
    lines.push('')
  }

  if (exp.whatToDo.length) {
    lines.push('## Recommended Actions')
    exp.whatToDo.forEach(function (action, i) {
      lines.push(i + 1 + '. ' + action)
    })
    lines.push('')
  }

  if (exp.educationalTip) {
    lines.push('## Educational Tip')
    lines.push(exp.educationalTip)
    lines.push('')
  }

  lines.push('---')
  lines.push('_Generated by CyberGuardian - Evidence First, AI Explains._')
  return lines.join('\n')
}

function downloadBlob(blob, filename) {
  const url = window.URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  link.remove()
  window.URL.revokeObjectURL(url)
}

const stamp = () => new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)

const btnBase =
  'inline-flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-medium transition-colors disabled:opacity-60'
const btnOutline = `${btnBase} border border-line bg-surface text-fg hover:bg-surface-2`
const btnPrimary = `${btnBase} bg-accent text-white hover:bg-accent-hover`

export default function AiExplanationCard({ explanation, scanData }) {
  const [feedback, setFeedback] = useState('')
  const [exportError, setExportError] = useState(null)
  const [pdfBusy, setPdfBusy] = useState(false)

  if (!explanation) return null

  const { summary, why, whatToDo, educationalTip } = normalizeExplanation(explanation)
  const markdownReport = buildMarkdownReport(scanData, explanation)
  const sev = getSeverity(scanData?.risk_assessment?.level)

  const flash = (msg) => {
    setFeedback(msg)
    setTimeout(() => setFeedback(''), 2000)
  }

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(markdownReport)
      setExportError(null)
      flash('copied')
    } catch {
      setExportError('The browser blocked clipboard access. Select the text and copy it manually.')
    }
  }

  const handleExport = async (kind) => {
    try {
      if (kind === 'md') {
        downloadBlob(new Blob([markdownReport], { type: 'text/markdown;charset=utf-8' }), `cyberguardian_report_${stamp()}.md`)
      } else if (kind === 'json') {
        const payload = JSON.stringify({ scan: scanData, explanation }, null, 2)
        downloadBlob(new Blob([payload], { type: 'application/json' }), `cyberguardian_report_${stamp()}.json`)
      } else if (kind === 'pdf') {
        setPdfBusy(true)
        const blob = await exportPdf(scanData)
        downloadBlob(blob, `cyberguardian_report_${stamp()}.pdf`)
      }
      setExportError(null)
      flash(kind)
    } catch (err) {
      setExportError(`Export failed: ${err?.message || 'unknown error'}`)
    } finally {
      setPdfBusy(false)
    }
  }

  return (
    <section
      className={`space-y-5 rounded-lg border border-l-4 border-line ${sev.borderL} bg-surface p-5`}
      aria-label="AI evidence interpretation"
    >
      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <h3 className="text-sm font-semibold">AI evidence interpretation</h3>
          <p className="text-xs text-muted">Written from the scan evidence above.</p>
        </div>

        <div className="flex flex-wrap items-center gap-2" role="group" aria-label="Report actions">
          <button type="button" onClick={handleCopy} className={btnPrimary}>
            {feedback === 'copied' ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
            {feedback === 'copied' ? 'Copied' : 'Copy summary'}
          </button>
          <button type="button" onClick={() => handleExport('md')} className={btnOutline}>
            <Download className="h-3.5 w-3.5" />
            Markdown
          </button>
          <button type="button" onClick={() => handleExport('json')} className={btnOutline}>
            <Download className="h-3.5 w-3.5" />
            JSON
          </button>
          <button type="button" onClick={() => handleExport('pdf')} disabled={pdfBusy} className={btnOutline}>
            <Download className="h-3.5 w-3.5" />
            {pdfBusy ? 'Preparing PDF…' : 'PDF'}
          </button>
        </div>
      </div>

      <div aria-live="polite" className="sr-only">
        {feedback === 'copied' && 'Summary copied to clipboard'}
        {['md', 'json', 'pdf'].includes(feedback) && 'Report exported'}
      </div>

      {exportError && (
        <div role="alert" className="flex items-start gap-2 rounded-md bg-sev-critical-bg p-3 text-xs text-sev-critical">
          <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
          <span>{exportError}</span>
        </div>
      )}

      {summary && (
        <div>
          <h4 className="mb-1.5 text-sm font-semibold">Summary</h4>
          <MarkdownRenderer content={summary} className="text-sm" />
        </div>
      )}

      {why.length > 0 && (
        <div>
          <h4 className="mb-1.5 text-sm font-semibold">Why this was flagged</h4>
          <ul className="list-disc space-y-1.5 pl-5 text-sm">
            {why.map((item, idx) => (
              <li key={idx}>{renderInline(item, 'why-' + idx)}</li>
            ))}
          </ul>
        </div>
      )}

      {whatToDo.length > 0 && (
        <div>
          <h4 className="mb-1.5 text-sm font-semibold">What to do</h4>
          <ol className="list-decimal space-y-1.5 pl-5 text-sm">
            {whatToDo.map((action, idx) => (
              <li key={idx}>{renderInline(action, 'act-' + idx)}</li>
            ))}
          </ol>
        </div>
      )}

      {educationalTip && (
        <div className="flex gap-3 rounded-md bg-accent-soft p-4">
          <Lightbulb className="mt-0.5 h-4 w-4 shrink-0 text-accent" aria-hidden="true" />
          <div className="min-w-0">
            <h4 className="mb-1 text-sm font-semibold">Educational tip</h4>
            <MarkdownRenderer content={educationalTip} className="text-sm" />
          </div>
        </div>
      )}
    </section>
  )
}
