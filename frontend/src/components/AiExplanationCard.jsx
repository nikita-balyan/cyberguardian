import React, { useState } from "react"
import {
  Sparkles,
  ShieldAlert,
  CheckCircle,
  Lightbulb,
  ArrowRight,
  Copy,
  Download,
  FileText,
  Check,
  AlertCircle,
} from "lucide-react"
import MarkdownRenderer, { renderInline } from "./MarkdownRenderer"

// Supports both the current API contract (why / what_to_do) and the legacy
// schema aliases (why_flagged / recommended_actions).
function normalizeExplanation(explanation) {
  if (!explanation) {
    return { summary: "", why: [], whatToDo: [], educationalTip: "" }
  }
  return {
    summary: explanation.summary || "",
    why: explanation.why || explanation.why_flagged || [],
    whatToDo: explanation.what_to_do || explanation.recommended_actions || [],
    educationalTip: explanation.educational_tip || "",
  }
}

// Builds a clean, portable Markdown report combining deterministic scan
// results with the grounded AI explanation for 1-click export / copy.
export function buildMarkdownReport(scanData, explanation) {
  const exp = normalizeExplanation(explanation)
  const lines = []
  const generatedAt = new Date().toISOString()

  lines.push("# CyberGuardian - AI Threat Explanation Report")
  lines.push("")
  lines.push("**Generated:** " + generatedAt)
  lines.push("")

  if (scanData) {
    const target =
      scanData.url ||
      scanData.message ||
      (scanData.evidence && scanData.evidence.extracted_text) ||
      "N/A"
    const score =
      scanData.risk_assessment && scanData.risk_assessment.score !== undefined
        ? scanData.risk_assessment.score
        : "N/A"
    const level =
      (scanData.risk_assessment && scanData.risk_assessment.level) || "N/A"
    const mlProb = scanData.evidence ? scanData.evidence.ml_probability : null

    lines.push("## Scan Overview")
    lines.push("- **Target:** " + target)
    lines.push("- **Risk Level:** " + level)
    lines.push("- **Composite Risk Score:** " + score + "/100")
    if (mlProb !== null && mlProb !== undefined) {
      lines.push("- **ML Phishing Probability:** " + (mlProb * 100).toFixed(1) + "%")
    }

    if (scanData.risk_assessment && scanData.risk_assessment.triggers && scanData.risk_assessment.triggers.length) {
      lines.push("")
      lines.push("### Deterministic Triggers")
      scanData.risk_assessment.triggers.forEach(function (t) {
        lines.push("- " + t)
      })
    }
    lines.push("")
  }

  lines.push("## Executive Summary")
  lines.push(exp.summary || "No summary provided.")
  lines.push("")

  if (exp.why.length) {
    lines.push("## Why Was This Flagged?")
    exp.why.forEach(function (item) {
      lines.push("- " + item)
    })
    lines.push("")
  }

  if (exp.whatToDo.length) {
    lines.push("## Recommended Actions")
    exp.whatToDo.forEach(function (action, i) {
      lines.push(i + 1 + ". " + action)
    })
    lines.push("")
  }

  if (exp.educationalTip) {
    lines.push("## Educational Tip")
    lines.push(exp.educationalTip)
    lines.push("")
  }

  lines.push("---")
  lines.push("_Generated by CyberGuardian - Evidence First, AI Explains._")
  return lines.join("\n")
}

export default function AiExplanationCard({ explanation, scanData }) {
  const [mutationFeedback, setMutationFeedback] = useState("")
  const [exportError, setExportError] = useState(null)

  if (!explanation) return null

  const { summary, why, whatToDo, educationalTip } = normalizeExplanation(explanation)
  const markdownReport = buildMarkdownReport(scanData, explanation)

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(markdownReport)
      setExportError(null)
      setMutationFeedback("copied")
      setTimeout(() => setMutationFeedback(""), 2000)
    } catch (err) {
      setExportError("Clipboard access was blocked by the browser. Please copy manually.")
    }
  }

  const handleExport = () => {
    try {
      const blob = new Blob([markdownReport], { type: "text/markdown;charset=utf-8" })
      const url = window.URL.createObjectURL(blob)
      const link = document.createElement("a")
      link.href = url
      const ts = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19)
      link.download = "cyberguardian_ai_report_" + ts + ".md"
      document.body.appendChild(link)
      link.click()
      link.remove()
      window.URL.revokeObjectURL(url)
      setExportError(null)
      setMutationFeedback("exported")
      setTimeout(() => setMutationFeedback(""), 2000)
    } catch (err) {
      setExportError("Failed to export the summary file.")
    }
  }

  return (
    <div className="bg-slate-900/80 border border-slate-800 rounded-2xl p-6 backdrop-blur-sm shadow-xl space-y-6">
      {/* Header Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-800">
        <div className="flex items-center space-x-3">
          <div className="bg-indigo-600/20 p-2.5 rounded-xl border border-indigo-500/30 text-indigo-400">
            <Sparkles className="w-5 h-5 animate-pulse" />
          </div>
          <div>
            <span className="text-xs uppercase font-bold tracking-widest text-indigo-400">
              Grounded AI Threat Analysis
            </span>
            <h3 className="text-lg font-bold text-white">AI Evidence Interpretation</h3>
          </div>
        </div>

        {/* Export & Copy Actions */}
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleCopy}
            className="inline-flex items-center space-x-1.5 px-3 py-2 rounded-xl bg-slate-950/80 border border-slate-800/80 hover:border-blue-500/50 hover:bg-slate-800/50 transition-colors text-xs font-semibold text-slate-300"
            title="Copy summary to clipboard as Markdown"
          >
            {mutationFeedback === "copied" ? (
              <Check className="w-4 h-4 text-emerald-400" />
            ) : (
              <Copy className="w-4 h-4 text-slate-400" />
            )}
            <span>{mutationFeedback === "copied" ? "Copied!" : "Copy Summary"}</span>
          </button>
          <button
            type="button"
            onClick={handleExport}
            className="inline-flex items-center space-x-1.5 px-3 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 transition-colors text-xs font-semibold text-white shadow-lg shadow-indigo-600/20"
            title="Export the AI summary as a Markdown report"
          >
            {mutationFeedback === "exported" ? (
              <Check className="w-4 h-4" />
            ) : (
              <Download className="w-4 h-4" />
            )}
            <span>Export Report</span>
          </button>
        </div>
      </div>

      {exportError && (
        <div className="p-3 bg-rose-950/30 border border-rose-900/50 rounded-xl flex items-center space-x-2.5 text-rose-300 text-xs">
          <AlertCircle className="w-4 h-4 flex-shrink-0 text-rose-400" />
          <span>{exportError}</span>
        </div>
      )}

      {/* Executive Summary (Markdown) */}
      {summary && (
        <div className="bg-slate-950/60 border border-slate-800/80 rounded-xl p-4">
          <span className="font-semibold text-blue-400 block mb-2 text-sm">Executive Summary</span>
          <MarkdownRenderer content={summary} className="text-sm" />
        </div>
      )}

      {/* Why is this flagged */}
      {why.length > 0 && (
        <div className="space-y-3">
          <div className="flex items-center space-x-2 text-rose-400 font-semibold text-sm">
            <ShieldAlert className="w-4 h-4" />
            <span>Why is this flagged? (Key Evidence Breakdown)</span>
          </div>
          <ul className="space-y-2">
            {why.map((item, idx) => (
              <li key={idx} className="flex items-start space-x-3 text-sm bg-slate-950/40 p-3 rounded-xl border border-slate-900">
                <span className="text-rose-400 font-bold mt-0.5">&bull;</span>
                <span className="text-slate-300">{renderInline(item, "why-" + idx)}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Recommended Actions */}
      {whatToDo.length > 0 && (
        <div className="space-y-3">
          <div className="flex items-center space-x-2 text-emerald-400 font-semibold text-sm">
            <CheckCircle className="w-4 h-4" />
            <span>Recommended Actions</span>
          </div>
          <div className="grid grid-cols-1 gap-2">
            {whatToDo.map((action, idx) => (
              <div key={idx} className="flex items-start space-x-3 text-sm bg-emerald-950/20 border border-emerald-900/30 p-3 rounded-xl text-slate-200">
                <ArrowRight className="w-4 h-4 text-emerald-400 mt-0.5 flex-shrink-0" />
                <span>{renderInline(action, "act-" + idx)}</span>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Educational Tip */}
      {educationalTip && (
        <div className="bg-gradient-to-r from-blue-950/40 to-cyan-950/40 border border-blue-800/40 rounded-xl p-4 flex items-start space-x-3">
          <div className="bg-blue-600/20 p-2 rounded-lg text-blue-400 mt-0.5">
            <Lightbulb className="w-4 h-4" />
          </div>
          <div className="flex-1 min-w-0">
            <span className="text-xs uppercase font-bold tracking-wider text-blue-400 block mb-1">
              Educational Tip
            </span>
            <MarkdownRenderer content={educationalTip} className="text-sm" />
          </div>
        </div>
      )}

      {/* Markdown source hint */}
      <div className="flex items-center space-x-2 text-[11px] text-slate-500 pt-1">
        <FileText className="w-3.5 h-3.5" />
        <span>Rendered with Markdown formatting. Use Copy Summary or Export Report for a portable .md file.</span>
      </div>
    </div>
  )
}
